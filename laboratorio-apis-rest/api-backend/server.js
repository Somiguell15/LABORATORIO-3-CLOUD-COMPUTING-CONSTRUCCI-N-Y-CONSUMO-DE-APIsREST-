
const express = require('express');
const cors = require('cors');
const { Pool } = require('pg');

const app = express();
const PORT = 5000;

app.use(express.json());
app.use(cors());

// Registrar las solicitudes en la terminal
app.use((req, res, next) => {
    console.log(`${req.method} ${req.originalUrl}`);
    next();
});

// Conexión con PostgreSQL usando las variables de Docker
const pool = new Pool({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT) || 5432,
    database: process.env.DB_NAME || 'tareasdb',
    user: process.env.DB_USER || 'tareasuser',
    password: process.env.DB_PASSWORD || 'tareas_dev_2026'
});

// Crear la tabla si todavía no existe

async function iniciarBaseDatos() {
    await pool.query(`
        CREATE TABLE IF NOT EXISTS tareas (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            texto TEXT NOT NULL
        )
    `);

    const resultado = await pool.query(
        'SELECT COUNT(*) AS total FROM tareas'
    );

    if (Number(resultado.rows[0].total) === 0) {
        await pool.query(`
            INSERT INTO tareas (texto) VALUES
            ('Aprender conceptos básicos de Docker'),
            ('Desplegar mi primera arquitectura de microservicios'),
            ('Revisar código de Miguel Angel Barrios Gil')
        `);

        console.log('Tareas iniciales insertadas.');
    }

    console.log('Base de datos PostgreSQL preparada.');
}


// GET: consultar todas las tareas
app.get('/api/tareas', async (req, res) => {
    try {
        const resultado = await pool.query(
            'SELECT id, texto FROM tareas ORDER BY id'
        );
        res.json(resultado.rows);
    } catch (error) {
        console.error(error);
        res.status(500).json({ error: 'Error al consultar las tareas.' });
    }
});

// POST: agregar una tarea
app.post('/api/tareas', async (req, res) => {
    const texto = req.body.texto;

    if (typeof texto !== 'string' || !texto.trim()) {
        return res.status(400).json({
            error: 'Debes escribir una tarea.'
        });
    }

    try {
        const resultado = await pool.query(
            'INSERT INTO tareas (texto) VALUES ($1) RETURNING id, texto',
            [texto.trim()]
        );
        res.status(201).json(resultado.rows[0]);
    } catch (error) {
        console.error(error);
        res.status(500).json({ error: 'Error al agregar la tarea.' });
    }
});

// DELETE global: vaciar toda la lista
app.delete('/api/tareas/limpiar', async (req, res) => {
    try {
        await pool.query('TRUNCATE TABLE tareas RESTART IDENTITY');
        res.json({
            mensaje: 'Todas las tareas fueron eliminadas correctamente.'
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({ error: 'Error al vaciar la lista.' });
    }
});

// DELETE: eliminar una tarea específica
app.delete('/api/tareas/:id', async (req, res) => {
    const id = Number(req.params.id);

    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ error: 'ID de tarea inválido.' });
    }

    try {
        const resultado = await pool.query(
            'DELETE FROM tareas WHERE id = $1 RETURNING id',
            [id]
        );

        if (resultado.rowCount === 0) {
            return res.status(404).json({
                error: 'No se encontró la tarea.'
            });
        }

        res.json({ mensaje: 'Tarea eliminada correctamente.' });
    } catch (error) {
        console.error(error);
        res.status(500).json({ error: 'Error al eliminar la tarea.' });
    }
});

// Iniciar el servidor después de preparar la base de datos
iniciarBaseDatos()
    .then(() => {
        app.listen(PORT, () => {
            console.log(`API REST corriendo en el puerto ${PORT}`);
        });
    })
    .catch(error => {
        console.error('No se pudo iniciar la base de datos:', error);
        process.exit(1);
    });